/* Page-only critical CSS. Run after editing any source stylesheet or Shuyi HTML.
 * Keep all Shuyi classes (including dynamic/error states), shared HTML classes,
 * theme controls, element rules and functional selectors. Preserve cascade and
 * every media query; never use viewport-dependent runtime coverage for pruning.
 */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const htmlPath = path.join(root, 'shuyi/index.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const sources = ['styles.css', 'shuyi/shuyi.css', 'studio-pages.css'];
const pageCSS = fs.readFileSync(path.join(root, 'shuyi/shuyi.css'), 'utf8');
const classes = new Set(['theme-toggle', 'skip-link', 'sr-only', 'is-short', 'is-standard', 'is-featured']);
for (const match of html.matchAll(/class="([^"]+)"/g)) match[1].split(/\s+/).forEach(c => classes.add(c));
for (const match of pageCSS.matchAll(/\.([a-zA-Z_][\w-]*)/g)) classes.add(match[1]);

function splitSelectors(text) {
  let depth = 0, start = 0, result = [];
  for (let i = 0; i < text.length; i++) {
    if ('(['.includes(text[i])) depth++;
    if (')]'.includes(text[i])) depth--;
    if (text[i] === ',' && depth === 0) { result.push(text.slice(start, i)); start = i + 1; }
  }
  return [...result, text.slice(start)];
}
function keep(selector) {
  // Unknown functional selectors are retained conservatively, not guessed.
  if (/:\w+\(/.test(selector)) return true;
  return [...selector.matchAll(/\.([a-zA-Z_][\w-]*)/g)].every(m => classes.has(m[1]));
}
function prune(css) {
  let output = '', start = 0, depth = 0, open = -1, quote = '';
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) { if (c === '\\') i++; else if (c === quote) quote = ''; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '{') { if (depth++ === 0) open = i; }
    else if (c === '}' && --depth === 0) {
      const selector = css.slice(start, open).trim();
      const body = css.slice(open + 1, i);
      if (/^@(media|supports|layer|container)\b/.test(selector)) {
        const nested = prune(body); if (nested) output += `${selector}{${nested}}`;
      } else if (selector.startsWith('@')) output += `${selector}{${body}}`;
      else {
        const selected = splitSelectors(selector).filter(keep).join(',');
        if (selected) output += `${selected}{${body}}`;
      }
      start = i + 1;
    }
  }
  if (depth || quote || css.slice(start).trim()) throw new Error('Unsupported/unbalanced CSS: refusing to generate');
  return output;
}
function compact(text) {
  let out = '', quote = '', space = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) {
      out += c;
      if (c === '\\') out += text[++i] || '';
      else if (c === quote) quote = '';
    } else if (/\s/.test(c)) space = true;
    else {
      if (space && out) out += ' ';
      space = false; out += c;
      if (c === '"' || c === "'") quote = c;
    }
  }
  return out.trim();
}
const css = sources.map(file => compact(prune(fs.readFileSync(path.join(root, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')))).join('\n');
const style = `<style id="shuyi-critical-css">\n/* Generated by tools/build-shuyi-critical-css.cjs; edit source stylesheets. */\n${css}\n</style>`;
if (html.includes('<style id="shuyi-critical-css">')) html = html.replace(/<style id="shuyi-critical-css">[\s\S]*?<\/style>/, style);
else html = html.replace('<link rel="stylesheet" href="../assets/styles/shuyi.min.css">', style);
// The theme must run before first paint (including persisted dark mode), but
// need not block HTML parsing on an extra network round trip. Embed the exact
// shared source so behavior stays identical and remains maintainable.
const theme = `<script id="shuyi-critical-theme">\n${fs.readFileSync(path.join(root, 'theme.js'), 'utf8').trim()}\n</script>`;
if (html.includes('<script id="shuyi-critical-theme">')) html = html.replace(/<script id="shuyi-critical-theme">[\s\S]*?<\/script>/, theme);
else html = html.replace('<script src="/theme.js"></script>', theme);
fs.writeFileSync(htmlPath, html);
console.log(JSON.stringify({sources, criticalBytes: Buffer.byteLength(css), retainedClasses: [...classes].sort()}, null, 2));

// Strip comments and collapse whitespace only outside quoted strings. Keep
// all selectors/declarations and their order: no heuristic CSS purging.
function compact(css) {
  let out = '', quote = '', whitespace = false;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) {
      out += c;
      if (c === '\\') out += css[++i] || '';
      else if (c === quote) quote = '';
    } else if (c === '/' && css[i + 1] === '*') {
      const end = css.indexOf('*/', i + 2);
      if (end < 0) throw new Error('Unclosed CSS comment');
      i = end + 1;
      whitespace = true;
    } else if (/\s/.test(c)) whitespace = true;
    else {
      if (whitespace && out) out += ' ';
      whitespace = false;
      out += c;
      if (c === '"' || c === "'") quote = c;
    }
  }
  if (quote) throw new Error('Unclosed CSS string');
  return out.trim();
}
async function main() {
  const manifest = [];
  for (const [source, widths, quality] of images) {
    for (const width of widths) {
      const target = source.replace(/\.[^.]+$/, `-responsive-${width}.webp`);
      const info = await sharp(path.join(root, source)).resize({ width, withoutEnlargement: true }).webp({ quality, effort: 6 }).toFile(path.join(root, target));
      manifest.push({ source, target, width: info.width, height: info.height, bytes: info.size });
    }
  }
  for (const [target, sources] of [
    ['assets/styles/course-preview.min.css', ['styles.css', 'studio-pages.css', 'courses/gen-ai-software-applications/performance.css']],
    ['assets/styles/shuyi.min.css', ['styles.css', 'shuyi/shuyi.css', 'studio-pages.css']]
  ]) {
    const css = (await Promise.all(sources.map(file => fs.readFile(path.join(root, file), 'utf8')))).map(compact).join('\n');
    await fs.mkdir(path.dirname(path.join(root, target)), { recursive: true });
    await fs.writeFile(path.join(root, target), `/* Generated by tools/build-performance-assets.cjs; edit source stylesheets. */\n${css}\n`);
  }
  console.log(JSON.stringify(manifest, null, 2));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
